export function getAllTopics() {
  return CHAPTERS.flatMap((c) =>
    c.topics.map((t) => ({ ...t, chapterId: c.id, chapterName: c.name }))
  );
}

export function getChapterById(chapterId) {
  return CHAPTERS.find((c) => c.id === Number(chapterId));
}

export function getChapterBySlug(slug) {
  return CHAPTERS.find((c) => c.slug === slug);
}

export function getTopicById(topicId) {
  for (const c of CHAPTERS) {
    const t = c.topics.find((x) => x.id === topicId);
    if (t) return { ...t, chapterId: c.id, chapterName: c.name };
  }
  return null;
}

export function getTotalTopicCount() {
  return CHAPTERS.reduce((sum, c) => sum + c.topics.length, 0);
}
